

def main() -> None:

    from _bootstrap import prepare_backend
    prepare_backend()
    from app.db.session import SessionLocal
    from app.db.models import Document
    from app.documents.indexer import search_chunks
    OWNER_ID = "67d69962-c200-4fb6-8248-bfd62885683e"
    DOCUMENT_ID = "4e7bee0b-5f93-4644-85c0-15c26e1021c8"
    db = SessionLocal()
    try:
        document = (
            db.query(Document)
            .filter(
                Document.id == DOCUMENT_ID,
                Document.owner_id == OWNER_ID,
                Document.deletion_status == "active",
            )
            .first()
        )

        if document is None:
            raise RuntimeError("Test document not found or not active")

        # Use the document owner as the authenticated actor.
        # The JWT is generated by the backend's normal helper.
        results = search_chunks(
            db=db,
            owner_id=OWNER_ID,
            query=f"Find information in {document.filename}",
            actor_id=OWNER_ID,
            actor_role="employee",
            k=4,
        )

        print(f"Document: {document.filename}")
        print(f"Document ID: {DOCUMENT_ID}")
        print(f"Results returned: {len(results)}")
        for i, result in enumerate(results, start=1):
            print(f"\nResult {i}:")
            print(f"  owner_id: {result.get('owner_id')}")
            print(f"  document_id: {result.get('document_id')}")
            print(f"  indexing_version: {result.get('indexing_version')}")
            print(f"  chunk_index: {result.get('chunk_index')}")
            print(f"  text: {result.get('text', '')[:300]}")

        wrong_owner = [r for r in results if r.get("owner_id") != OWNER_ID]
        wrong_document_version = [
            r for r in results
            if r.get("document_id") == DOCUMENT_ID
            and r.get("indexing_version") != document.active_version_id
        ]

        print("\nValidation:")
        print(f"No cross-owner results: {not wrong_owner}")
        print(f"No stale version of test document: {not wrong_document_version}")

        if wrong_owner or wrong_document_version:
            raise AssertionError("Search results failed validation.")
    finally:
        db.close()


if __name__ == "__main__":
    main()
